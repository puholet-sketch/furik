def build(fixed: bool) -> Path:
    doc = Document()
    setup_doc(doc)
    if fixed:
        title_block(
            doc,
            "с иностранным гражданином (срочный; ст. 59 ч. 2 ТК РФ — ИП ≤ 35 работников)",
        )
        parties(doc)
        subject_fixed(doc)
        out = DOCS / "трудовой-договор-срочный-иностранец.docx"
    else:
        title_block(
            doc,
            "с иностранным гражданином (на неопределённый срок — рекомендуемый вариант)",
        )
        parties(doc)
        subject_indefinite(doc)
        out = DOCS / "трудовой-договор-иностранец.docx"
    foreign_status(doc)
    duties(doc)
    pay(doc)
    hours(doc)
    termination(doc, fixed=fixed)
    final(doc)
    doc.save(out)
    return out


def main() -> None:
    a = build(False)
    b = build(True)
    print(f"OK {a}")
    print(f"OK {b}")


if __name__ == "__main__":
    main()
