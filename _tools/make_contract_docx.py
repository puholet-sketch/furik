def set_run_font(run, size=11, bold=False, color=C_TEXT, name="Calibri"):
    run.font.name = name
    run._element.rPr.rFonts.set(qn("w:eastAsia"), name)
    run.font.size = Pt(size)
    run.font.bold = bold
    run.font.color.rgb = color


def add_para(doc, text, *, size=11, bold=False, color=C_TEXT, align="left", space_after=6, space_before=0):
    p = doc.add_paragraph()
    p.paragraph_format.space_after = Pt(space_after)
    p.paragraph_format.space_before = Pt(space_before)
    p.paragraph_format.line_spacing_rule = WD_LINE_SPACING.MULTIPLE
    p.paragraph_format.line_spacing = 1.15
    if align == "center":
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    elif align == "justify":
        p.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
    elif align == "right":
        p.alignment = WD_ALIGN_PARAGRAPH.RIGHT
    run = p.add_run(text)
    set_run_font(run, size=size, bold=bold, color=color)
    return p


def add_section_title(doc, text):
    p = add_para(doc, text.upper(), size=12, bold=True, color=C_ACCENT, space_before=12, space_after=4)
    # bottom border
    pPr = p._p.get_or_add_pPr()
    pBdr = OxmlElement("w:pBdr")
    bottom = OxmlElement("w:bottom")
    bottom.set(qn("w:val"), "single")
    bottom.set(qn("w:sz"), "12")
    bottom.set(qn("w:space"), "4")
    bottom.set(qn("w:color"), "C00000")
    pBdr.append(bottom)
    pPr.append(pBdr)
    return p


def add_meta_table(doc, rows):
    table = doc.add_table(rows=len(rows), cols=2)
    table.style = "Table Grid"
    for i, (k, v) in enumerate(rows):
        cell0, cell1 = table.rows[i].cells
        cell0.text = ""
        cell1.text = ""
        r0 = cell0.paragraphs[0].add_run(k)
        set_run_font(r0, size=10, bold=True, color=C_H1)
        r1 = cell1.paragraphs[0].add_run(v)
        set_run_font(r1, size=10, color=C_TEXT)
        # header-ish first column bg light gray
        shading = OxmlElement("w:shd")
        shading.set(qn("w:fill"), "F5F5F5")
        shading.set(qn("w:val"), "clear")
        cell0._teProp = cell0._tc.get_or_add_tcPr()
        cell0._tc.get_or_add_tcPr().append(shading)
        if i % 2 == 1:
            shading2 = OxmlElement("w:shd")
            shading2.set(qn("w:fill"), "FFF0F0")
            shading2.set(qn("w:val"), "clear")
            cell1._tc.get_or_add_tcPr().append(shading2)
    return table


